import test from 'node:test';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { Editor } from '@tiptap/core';
import { editorExtensions, createNoteEditor } from '../src/editor.js';
import { validateDocument, documentText, plainDocument } from '../public/assets/document.js';
import { encryptVault, decryptVault } from '../public/assets/crypto.js';
import { emptyVault, makeNote, validateVault } from '../public/assets/model.js';
const dom = new JSDOM('<!doctype html><body><div id="editor"></div></body>', { url:'http://localhost/' });
for (const key of ['window','document','navigator','DOMParser','Node','HTMLElement','MutationObserver','getComputedStyle']) Object.defineProperty(globalThis,key,{value:dom.window[key],configurable:true});
globalThis.requestAnimationFrame = callback => setTimeout(callback, 0); globalThis.cancelAnimationFrame = clearTimeout;
const rect = { top:0,left:0,bottom:0,right:0,width:0,height:0,x:0,y:0 };
dom.window.Range.prototype.getClientRects = () => [];
dom.window.Range.prototype.getBoundingClientRect = () => rect;
const makeEditor = () => new Editor({ element:document.createElement('div'), extensions:editorExtensions(), content:plainDocument('Alpha\nBeta'), injectCSS:false });
test('formatting, clickable tasks, tables and undo survive encrypted reload', async () => {
  const editor = makeEditor();
  editor.commands.setTextSelection({from:1,to:6});
  for (const command of ['toggleBold','toggleItalic','toggleUnderline','toggleStrike']) editor.commands[command]();
  assert.deepEqual(editor.getJSON().content[0].content[0].marks.map(mark=>mark.type).sort(), ['bold','italic','strike','underline']);
  editor.commands.setTextSelection(8); editor.commands.toggleTaskList();
  const checkbox = editor.view.dom.querySelector('input[type=checkbox]'); assert.ok(checkbox);
  checkbox.checked = true; checkbox.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
  assert.ok(JSON.stringify(editor.getJSON()).includes('"checked":true'));
  editor.commands.setTextSelection(editor.state.doc.content.size - 2);
  editor.commands.insertTable({rows:2,cols:2,withHeaderRow:false});
  assert.equal(editor.view.dom.querySelectorAll('td').length,4);
  editor.commands.insertContent('Cell content'); editor.commands.addRowAfter();
  assert.equal(editor.view.dom.querySelectorAll('td').length,6);
  editor.commands.addColumnAfter(); assert.equal(editor.view.dom.querySelectorAll('td').length,9);
  editor.commands.deleteColumn(); assert.equal(editor.view.dom.querySelectorAll('td').length,6);
  const doc=editor.getJSON(); validateDocument(doc);
  const vault=emptyVault(); vault.notes.push({...makeNote(), document:doc, body:documentText(doc)}); validateVault(vault);
  const key=await crypto.subtle.generateKey({name:'AES-GCM',length:256},false,['encrypt','decrypt']);
  const restored=await decryptVault(key,await encryptVault(key,vault)); validateVault(restored); assert.deepEqual(restored.notes[0].document,JSON.parse(JSON.stringify(doc)));
  editor.destroy();
  const reopened = new Editor({element:document.createElement('div'),extensions:editorExtensions(),content:restored.notes[0].document,injectCSS:false});
  assert.equal(reopened.view.dom.querySelectorAll('td').length,6);
  reopened.commands.insertContent('Temporary'); reopened.commands.undo(); assert.equal(documentText(reopened.getJSON()),documentText(doc)); reopened.destroy();
});
test('schema strips active pasted HTML and rejects oversized transactions', () => {
  const editor=makeEditor();
  editor.commands.setContent('<p onclick="alert(1)"><strong>Safe</strong><img src="https://untrusted.example/tracker"><script>alert(1)</script><a href="javascript:alert(1)">Text</a></p>');
  assert.equal(editor.view.dom.querySelectorAll('img,script,a,[onclick]').length,0); validateDocument(editor.getJSON());
  const before=editor.getJSON(); editor.commands.insertContent('x'.repeat(500001)); assert.deepEqual(editor.getJSON(),before); editor.destroy();
});
test('note switching and lock discard editor history and plaintext; trash checkbox is read-only', () => {
  const element=document.createElement('div'); let updates=0;
  const bridge=createNoteEditor(element,{onChange(){updates++;}});
  bridge.setNote({...makeNote(),id:'a',body:'Private A'}); bridge.command('bold');
  bridge.setNote({...makeNote(),id:'b',body:'Private B'}); assert.equal(element.textContent,'Private B');
  bridge.setNote({...makeNote(),id:'b',body:'Private B',deleted:1}); assert.equal(bridge.command('checklist'),false);
  assert.equal(element.querySelector('[contenteditable]').getAttribute('contenteditable'),'false');
  bridge.clear(); assert.equal(element.textContent,''); assert.equal(element.childElementCount,0); assert.equal(updates,0);
});
